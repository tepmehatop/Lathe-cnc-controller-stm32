/**
 * @file    els_config.h
 * @brief   ELS — Электронная Гитара Токарного Станка
 *          ЕДИНЫЙ ФАЙЛ НАСТРОЕК
 *
 * Всё, что нужно поменять под свой станок, — здесь:
 *   1. Что подключено: откуда берутся координаты, какой дисплей.
 *   2. Механика станка: энкодер, моторы, винты, микрошаг.
 *   3. Подачи, ускоренные ходы, РГИ (ручной энкодер), отскоки.
 *   4. Линейки, подключённые напрямую к STM32.
 *   5. Скорости связи.
 * Пины (какой провод куда) — в Core/e2/e2_pins.h.
 * Пояснения ко всем параметрам — docs/README.md, раздел «Настройка».
 *
 * Блоки 2–3 — параметры оригинальной прошивки 7e2 (те же имена и значения
 * по умолчанию), поэтому советы с форума chipmaker.ru к ним применимы.
 */

#pragma once

// ============================================================================
// 1. ЧТО ПОДКЛЮЧЕНО
// ============================================================================

// ── Источник координат: откуда STM32 знает положение каретки и суппорта ──────
// Подробно о линейках, схемах подключения и настройке — docs/scales/README.md
#define POS_SOURCE_STEPS        0   // без линеек: позиция по шагам моторов (как в 7e2 без DRO)
#define POS_SOURCE_DRO_UART     1   // блок DRO HS800-2 по UART (линейки подключены к блоку)
#define POS_SOURCE_SCALES       2   // линейки напрямую к STM32, без блока DRO

#ifndef ELS_POS_SOURCE   // можно переопределить флагом -D при сборке
#define ELS_POS_SOURCE          POS_SOURCE_DRO_UART
#endif

/** Драйвер блока DRO HS800-2 включён только в режиме DRO_UART */
#define USE_DRO_HS800           (ELS_POS_SOURCE == POS_SOURCE_DRO_UART)

// ── Сенсорный дисплей ESP32 (по UART) ────────────────────────────────────────
// Прошивка дисплея собирается отдельно под свой размер: env jc4827w543 (4.3")
// или jc8012p4a1c (10.1") — см. DISPLAYS.md. При старте дисплей сообщает свой
// тип; если он не совпадает с выбранным здесь, STM32 пишет предупреждение
// в отладочный порт и показывает его на дисплее.
#define DISPLAY_TYPE_NONE       0   // без ESP32-дисплея (только LCD2004)
#define DISPLAY_TYPE_4_3        43  // JC4827W543, 4.3" 480×272
#define DISPLAY_TYPE_7_0        70  // 7" — зарезервировано, пока не поддерживается
#define DISPLAY_TYPE_10_1       101 // JC8012P4A1C, 10.1" 1280×800

#ifndef ELS_DISPLAY_TYPE   // можно переопределить флагом -D при сборке
#define ELS_DISPLAY_TYPE        DISPLAY_TYPE_10_1
#endif

#if ELS_DISPLAY_TYPE == DISPLAY_TYPE_7_0
    #error "Дисплей 7\" пока не поддерживается — выберите DISPLAY_TYPE_4_3 или DISPLAY_TYPE_10_1"
#endif

#define USE_ESP32_DISPLAY       (ELS_DISPLAY_TYPE != DISPLAY_TYPE_NONE)

// ── Текстовый дисплей LCD2004 по I2C (запасной) ──────────────────────────────
// Если не подключён — прошивка это определит сама и работает без него.
#define LCD_I2C_ADDR            0x27    // адрес модуля PCF8574 (бывает 0x3F)

// ============================================================================
// 2. МЕХАНИКА СТАНКА
// ============================================================================
#define ENC_LINE_PER_REV     1800     // Кол-во линий энкодера на 1 оборот шпинделя
#define MOTOR_Z_STEP_PER_REV 200      // Кол-во шагов двигателя на оборот винта Z, продольная (200 для ШД с шагом 1,8 градуса)
#define SCREW_Z              200      // Шаг продольного винта Z в сотках, (2мм)
#define McSTEP_Z             4        // Микрошаг, ось Z, продольная (положение переключателей на драйвере 800)
#define MOTOR_X_STEP_PER_REV 200      // Кол-во шагов двигателя на оборот винта X, поперечная (200 для ШД с шагом 1,8 градуса)
#define SCREW_X              100      // Шаг поперечного винта X в сотках, (1мм)
#define McSTEP_X             4        // Микрошаг, ось X, поперечная (положение переключателей на драйвере 800)

// ============================================================================
// 3. ПОДАЧИ, УСКОРЕНИЯ, ОТСКОКИ, РГИ
// ============================================================================
#define REBOUND_X            200      // Отскок резца в микрошагах, для авторезанья, должен быть больше люфта поперечки (0,25мм)
#define REBOUND_Z            200      // Отскок резца в микрошагах, для авторезанья, должен быть больше люфта продольки (0,5мм)
#define THRD_ACCEL           24       // К.деления с которого будем ускоряться на Резьбах, THRD_ACCEL + Ks должен быть < 255
#define FEED_ACCEL           3        // Жесткость разгона на подачах, бОльше значение - короче разгон
#define MIN_FEED             1        // Желаемая минимальная подача  в сотках/оборот, 0.01мм/об
#define MAX_FEED             25       // Желаемая максимальная подача в сотках/оборот, 0.25мм/об
#define MIN_aFEED            10       // Желаемая минимальная подача  в mm/минуту, 10мм/мин
#define MAX_aFEED            400      // Желаемая максимальная подача в mm/минуту, 400мм/мин
#define Excess_Lag           2        // Сколько лишних микрошагов набегает на отскоке оси Х в режиме "ШАР"
#define PASS_FINISH          2        // Количество чистовых проходов, по умолчанию, после автоцикла в режиме "Резьба"

// Ускоренные перемещения
#define MAX_RAPID_MOTION     50                      // Меньше - бОльшая конечная скорость
#define MIN_RAPID_MOTION    (MAX_RAPID_MOTION + 190) // Больше - мЕньшая начальная скорость, max 255
#define REPEAt              (McSTEP_Z * 1)           // Кол-во повторов для постоянной скорости в пределах полного шага
                                                     // Длительность разгона = 100/2*REPEAT(2)/Microstep(2) = 50 полных шагов цикл ускорения
// Ручной энкодер (100 линий)
#define HC_SCALE_1           1        // 1-e положение
#define HC_SCALE_10          10       // 2-e положение
#define HC_START_SPEED_1     250      // старт РГИ, 250000/(250+1)/800*60/2 = 37rpm
#define HC_MAX_SPEED_1       150      // максимум скорости РГИ, 250000/(150+1)/800*60/2 = 62rpm
#define HC_START_SPEED_10    150      // старт РГИ, 250000/(150+1)/800*60/2 = 62rpm
#define HC_MAX_SPEED_10      50       // максимум скорости РГИ, 250000/(23+1)/800*60/2 = 391rpm
#define HC_X_DIR             1        // 1-поперечка по часовой, 0-против
#define HC_Z_DIR             0        // 1-продолная по часовой, 0-против

// Настройка линейки
#define LIN_X               200       // корректировка изменений масштаба оси X на диаметр
#define BT_X                10        // масштаб 10 = 0.10mm 20 = 0.20mm и т. д., в режиме линейка кнопками влево-вправо

// Настройка мигания лимитов
#define BLINC_TIME          10
#define BLINC_ON_OFF        5

// ============================================================================
// 4. ЛИНЕЙКИ НАПРЯМУЮ — используется при ELS_POS_SOURCE == POS_SOURCE_SCALES
// Какие бывают линейки, схемы сопряжения, распиновка разъёмов, примеры
// настройки под конкретные модели — docs/scales/README.md
// ============================================================================

/** Типы линеек (по протоколу/выходу, а не по технологии датчика) */
#define SCALE_NONE              0   // нет линейки — ось считается по шагам мотора
#define SCALE_QUADRATURE        1   // стеклянные и магнитные: квадратура A/B
                                    //   (TTL 5 В или RS-422 через приёмник)
#define SCALE_SYLVAC48          2   // ёмкостные китайские 1.5 В, 2×24 бит (Sylvac),
                                    //   20480 имп/дюйм, такт от линейки
#define SCALE_BIN6              3   // ёмкостные 24 бит BIN6 (Shahe, штангенциркули),
                                    //   0.01 мм / 0.0005", такт от линейки
#define SCALE_IGAGING21         4   // iGaging EZ-View / AccuRemote / DigiMag 3 В,
                                    //   21 бит, 2560 имп/дюйм, такт от STM32
#define SCALE_DIGIMATIC         5   // Mitutoyo Digimatic (SPC): REQ/CLK/DATA, BCD

// ── Ось Z: каретка, продольная ──
#ifndef SCALE_Z_TYPE   // можно переопределить флагом -D при сборке
#define SCALE_Z_TYPE            SCALE_QUADRATURE
#endif
/** Только для SCALE_QUADRATURE: перемещение на 1 импульс (с учётом ×4) в нанометрах.
 *  Типично: 5 мкм → 5000, 1 мкм → 1000, 10 мкм → 10000. Указано на линейке/в паспорте. */
#define SCALE_Z_NM_PER_COUNT    5000
/** 1 = сменить направление счёта (если при движении влево значение растёт не туда) */
#define SCALE_Z_INVERT          0
/** Только для протоколов с тактом (SYLVAC48/BIN6/IGAGING21/DIGIMATIC):
 *  1 = схема сопряжения инвертирует сигналы (один транзистор), 0 = не инвертирует
 *  (компаратор/буфер). См. схему в docs/scales/README.md */
#ifndef SCALE_Z_SIGNAL_INVERT   // можно переопределить флагом -D при сборке
#define SCALE_Z_SIGNAL_INVERT   0
#endif

// ── Ось X: суппорт, поперечная ──
#ifndef SCALE_X_TYPE   // можно переопределить флагом -D при сборке
#define SCALE_X_TYPE            SCALE_QUADRATURE
#endif
#define SCALE_X_NM_PER_COUNT    5000
#define SCALE_X_INVERT          0
#ifndef SCALE_X_SIGNAL_INVERT   // можно переопределить флагом -D при сборке
#define SCALE_X_SIGNAL_INVERT   0
#endif

/** Цифровой фильтр входов квадратуры (0..15, поле ICxF таймера): подавляет
 *  иголки от помех ЧП/моторов. 3 = 8 отсчётов по 12 нс ≈ 0.1 мкс — с запасом
 *  пропускает 1 мкм-линейку на 1 м/с. Увеличить, если счёт «плывёт» от помех. */
#define SCALE_QUAD_FILTER       3

/** Разъём линейки: A/CLK, B/DATA, REQ.
 *  Для квадратуры пины фиксированы таймерами (TIM2 — Z, 32 бит; TIM3 — X).
 *  Все сигнальные пины толерантны к 5 В. PA15/PB3/PB4 — пины JTAG:
 *  прошивка через SWD (ST-Link) ими не пользуется.
 *  REQ (только Digimatic) — на выводах блока DRO: в режиме линеек он не нужен. */
#define SCALE_Z_PIN_A           PA15    // TIM2_CH1 / такт
#define SCALE_Z_PIN_B           PB3     // TIM2_CH2 / данные
#define SCALE_Z_PIN_REQ         PA2     // REQ (только Digimatic)
#define SCALE_X_PIN_A           PB4     // TIM3_CH1 / такт
#define SCALE_X_PIN_B           PB5     // TIM3_CH2 / данные
#define SCALE_X_PIN_REQ         PA3     // REQ (только Digimatic)

// ============================================================================
// 5. СВЯЗЬ
// ============================================================================
#define DRO_UART_BAUD           57600   // блок DRO HS800-2 → STM32 (USART2, PA3)
#define DISP_UART_BAUD          57600   // STM32 ↔ дисплей ESP32 (USART3, PB10/PB11)
#define DEBUG_UART_BAUD         115200  // отладочный порт / команды эмуляции (USART1, PA9/PA10)

// ============================================================================
// 6. ПЕРЕМЕННЫЙ РЕЗИСТОР ПОДАЧИ (как в 7e2: ручка на пульте, вход PC1)
// ============================================================================
/** 1 — переменник подключён: подача синхронная/асинхронная задаётся ручкой.
 *  0 — переменника нет: подача задаётся кнопками/дисплеем. Без переменника вход
 *  «висит в воздухе», и подача скакала бы сама — поэтому его надо выключить здесь. */
#define USE_FEED_POT            0

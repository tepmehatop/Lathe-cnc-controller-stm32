// ============================================================================
// 3. ПОДАЧИ, УСКОРЕНИЯ, ОТСКОКИ, РГИ
// ============================================================================
#define REBOUND_X            200      // Отскок резца в микрошагах, для авторезанья, должен быть больше люфта поперечки (0,25мм)
#define REBOUND_Z            200      // Отскок резца в микрошагах, для авторезанья, должен быть больше люфта продольки (0,5мм)
// Компенсация люфта винтов (нет в 7e2). При смене направления прошивка делает на столько микрон
// больше шагов, и каретка приходит точно в заданную точку — в ручных движениях, автоциклах, от РГИ.
// Без компенсации (0, как у автора) ноль цикла надо брать подводом резца к детали, иначе глубина
// меньше на величину люфта (проверено моделью: SIM_BACKLASH=1 bash tools/run_e2_sim.sh).
// Как измерить: индикатор на каретку, подвести в одну сторону, обнулить, двигать в обратную —
// сколько шагов мотора прошло до начала движения стрелки, столько и люфт.
// Кнопки упоров (BACKLOG-022). У автора упор ставится, только если ФИЗИЧЕСКИЙ переключатель
// подрежима стоит в «Ручной» (нельзя переставить упор в автоцикле). 1 — достаточно выбрать «Ручной»
// и на экране (работает без переключателя); 0 — только переключатель, как в 7e2.
// Синхронная подача (BACKLOG-020). У автора таймер делает шаг раз в (делитель + 1) импульсов энкодера,
// а делитель считается как идеальный — подача выходит на 6–10 % меньше заданной (0.20 → 0.18 мм/об).
// 1 — лишний период вычитается, подача равна заданной; 0 — как у автора. На резьбу не влияет.
#ifndef FEED_EXACT
#define FEED_EXACT                  1
#endif

#ifndef LIMITS_BY_SELECTED_SUBMODE
#define LIMITS_BY_SELECTED_SUBMODE  1
#endif

// Линейки в автоциклах (BACKLOG-025; работают, если есть блок DRO или линейки). Доводка X: после врезания,

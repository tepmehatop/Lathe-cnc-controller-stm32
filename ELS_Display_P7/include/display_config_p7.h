/*
 * display_config_p7.h
 * Конфигурация 7" Guition JC1060P470 (ESP32-P4 + ESP32-C6, 1024×600, JD9165 MIPI-DSI, тач GT911).
 *
 * НА ЖЕЛЕЗЕ НЕ ПРОВЕРЯЛОСЬ (у владельца проекта этого дисплея нет). Ноги и тайминги — из открытых
 * конфигураций платы (ESPHome mipi_dsi «JC1060P470», проект EspControl) и совпадают с 10.1" там,
 * где плата та же (подсветка, тач, UART0). Замечания с реального дисплея — в BACKLOG-037.
 *
 * Две панели под одним названием (сзади на корпусе метка «V2» — новая панель, без метки — старая):
 *   P7_PANEL_V2 = 0 — старая панель (env jc1060p470)
 *   P7_PANEL_V2 = 1 — панель V2 (env jc1060p470_v2; на чипе ESP32-P4 ревизии 3.x — env jc1060p470_v3)
 * Не та прошивка — белый экран с полосой шума; тогда шить другую.
 */

#pragma once

#ifndef P7_PANEL_V2
#define P7_PANEL_V2 0
#endif

// ─── Параметры дисплея ─────────────────────────────────────────────────────
// Панель сама «лежит» (1024×600), поворот не нужен, но стоит вверх ногами — картинка
// и тач переворачиваются на 180° (в ESPHome у этой платы rotation: 180).
#define P7_LCD_H_RES   1024
#define P7_LCD_V_RES   600
#ifndef P7_ROT180
#define P7_ROT180      1
#endif

// ─── GPIO ──────────────────────────────────────────────────────────────────
#define P7_LCD_RST     0    // LCD_RST по схеме JC1060P470C_I_W_Y (FPC1, вывод 4)
#define P7_LCD_BL      23   // подсветка (как у 10.1")

// Тач GT911 (I2C, как у 10.1")
#define P7_TP_SDA      7
#define P7_TP_SCL      8
#define P7_TP_RST      22
#define P7_TP_INT      21

// UART до STM32: UART0 ESP32-P4 (TX GPIO37, RX GPIO38) — как разъём «INPUT» у 10.1".
// GPIO14..19 — SDIO до ESP32-C6 (Wi-Fi), не использовать.
#define P7_UART_RX_PIN 38
#define P7_UART_TX_PIN 37

// ─── LVGL ──────────────────────────────────────────────────────────────────
#define P7_DRAW_BUF_LINES  60   // строк по 1024 px во внутренней SRAM
